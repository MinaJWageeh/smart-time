// Run with playwright-cli run-code --filename tests/workspace-browser.js
// Uses synthetic client data in an isolated browser profile.
async (page) => {
  const suffix = Date.now().toString(36);
  const client = `Test client ${suffix}`, project = `Test project ${suffix}`, note = `Contract ${suffix}`;
  const fileName = `client-brief-${suffix}.txt`;
  const button = name => page.getByRole('button', { name, exact: true });
  await button('New client').click();
  await page.getByRole('textbox', { name: 'Client name', exact: true }).fill(client);
  await button('Create client').click();
  await button('Project').click();
  await page.getByRole('textbox', { name: 'Project name', exact: true }).fill(project);
  await button('Create project').click();
  await button('New note').click();
  await page.getByRole('textbox', { name: 'Untitled Note', exact: true }).fill(note);
  await page.getByRole('textbox', { name: 'Note tags', exact: true }).fill('contract, design');
  await page.getByRole('textbox', { name: 'Note tags', exact: true }).press('Enter');
  await page.getByLabel('Attach file to note', { exact: true }).setInputFiles({ name: fileName, mimeType: 'text/plain', buffer: Buffer.from('A synthetic client brief for the workspace test.') });
  await page.getByRole('button', { name: fileName, exact: true }).waitFor();
  await button('Clients & Projects').click();
  await page.getByRole('status').filter({ hasText: /^Saved locally$/ }).waitFor();
  await page.reload();
  await button(note).waitFor();
  await page.getByRole('combobox', { name: 'Filter by client', exact: true }).selectOption({ label: client });
  await page.getByRole('textbox', { name: 'Search workspace', exact: true }).fill(note);
  if (await page.locator('.ws-note').count() !== 1) throw new Error('Client/search filtering failed.');
  await page.getByRole('textbox', { name: 'Search workspace', exact: true }).fill('');
  await page.getByRole('tab', { name: 'Files', exact: true }).click();
  await page.getByText(fileName, { exact: true }).waitFor();
  await button('Organize').click();
  await page.getByLabel('Tags, separated by commas', { exact: true }).fill('contract, reference');
  await button('Save file details').click();
  await button('#reference').waitFor();
  const backupPromise = page.waitForEvent('download');
  await button('Back up').click();
  const download = await backupPromise;
  const path = await download.path();
  let raw = '';
  for await (const chunk of await download.createReadStream()) raw += chunk.toString('utf8');
  const backup = JSON.parse(raw);
  const file = backup.files.find(f => backup.workspace.attachments.some(a => a.id === f.id && a.name === fileName));
  if (!file || Buffer.from(file.bytes).toString('utf8') !== 'A synthetic client brief for the workspace test.') throw new Error('Backup file bytes did not round-trip.');
  await page.getByRole('tab', { name: 'Notes', exact: true }).click();
  await button(`Move ${note} to trash`).click();
  await page.getByRole('tab', { name: 'Trash', exact: true }).click();
  await button(`Restore ${note}`).click();
  await page.getByRole('tab', { name: 'Notes', exact: true }).click();
  await button(note).waitFor();
  await page.getByLabel('Choose backup to restore', { exact: true }).setInputFiles(path);
  await page.getByRole('dialog', { name: 'Restore this workspace?', exact: true }).waitFor();
  await button('Restore workspace').click();
  await page.getByRole('status').filter({ hasText: 'Backup restored. Your previous workspace is available under Undo restore.' }).waitFor();
  await page.reload(); await button(note).waitFor();
  await page.getByRole('tab', { name: 'Files', exact: true }).click();
  await page.getByText(fileName, { exact: true }).waitFor();
  await page.getByLabel('Choose backup to restore', { exact: true }).setInputFiles({ name: 'invalid-backup.json', mimeType: 'application/json', buffer: Buffer.from('{"format":"wrong"}') });
  await page.getByRole('alert').filter({ hasText: 'not a supported Smart Time backup' }).waitFor();
  await page.getByText(fileName, { exact: true }).waitFor();
  return { passed: ['client/project creation', 'note tags', 'attachment upload', 'reload persistence', 'client/search filters', 'file tags', 'backup bytes', 'trash recovery', 'backup restore', 'malformed backup rejection'], client, project, note };
}
